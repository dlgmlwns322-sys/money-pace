// 지출 카테고리 자동 분류(2026-09-26 사용자 지정 8개). 앱(index.html)과 테스트(node)가 함께 쓴다.
// 가맹점 이름에 든 단어로 나눈다. 겹치면 위에서부터 먼저 맞는 것(배달 → 피시방 → 카페 → 편의점 → 병원 → 쇼핑 → 식비. 'PC카페'는 피시방).
// 못 맞히면 '기타'. 사용자가 한 번 정한 가맹점은 앱이 기억해서 이 규칙보다 먼저 쓴다.
(function (root) {
  const CATS = ['식비', '카페', '편의점', '쇼핑', '병원', '배달', '피시방', '기타'];
  const RULES = [
    ['배달', /배달의민족|배민|쿠팡이츠|요기요|땡겨요|위메프오/],
    ['피시방', /pc방|피시방|pc카페|피씨방/],
    ['카페', /커피|카페|cafe|coffee|스타벅스|메가mgc|메가커피|투썸|이디야|빽다방|컴포즈|폴바셋|할리스|공차|파스쿠찌|엔제리너스|더벤티|매머드|베이커리|파리바게뜨|뚜레쥬르|빵집|제과/],
    ['편의점', /gs25|지에스25|씨유|세븐일레븐|7-?eleven|이마트24|미니스톱|씨스페이스|편의점/],
    ['병원', /병원|의원|치과|한의원|약국|정형외과|내과|피부과|이비인후과|안과|소아과|산부인과|비뇨기과|가정의학과|신경외과|재활의학과/],
    ['쇼핑', /쿠팡|네이버페이|무신사|올리브영|다이소|11번가|지마켓|g마켓|옥션|이마트|홈플러스|롯데마트|마트|29cm|에이블리|지그재그|알리익스프레스|테무|유니클로|zara|h&m|교보문고|yes24|알라딘/],
    ['식비', /식당|김밥|국밥|치킨|버거|맥도날드|롯데리아|맘스터치|분식|떡볶이|고기|초밥|스시|한솥|본죽|도시락|국수|냉면|짜장|중국집|반점|피자|샐러드|서브웨이|쌀국수|찌개|삼겹|갈비|곱창|족발|보쌈|돈까스|돈가스|라멘|우동|샤브|뷔페|푸드|반찬/],
  ];
  // 이름 정리: 공백·괄호 제거, 소문자(영문)
  const norm = (s) => String(s || '').replace(/[\s()（）]/g, '').toLowerCase();
  // 쿠팡이츠는 쇼핑(쿠팡)보다 배달이 먼저라 순서대로 보면 된다
  function categorize(name) {
    const n = norm(name);
    if (!n) return '기타';
    for (const [cat, re] of RULES) {
      if (re.test(n)) return cat;
      // 편의점 CU: 공백을 지우기 전 원래 이름에서 영문 단어로 따로 있을 때만('CU 강남점' O, 'cute' X)
      if (cat === '편의점' && /(^|[^a-z])cu([^a-z]|$)/.test(String(name).toLowerCase())) return cat;
    }
    return '기타';
  }
  // 사용자가 정한 가게를 기억할 때의 키: 공백만 지우고 소문자(괄호 등은 남겨 '가(나)'와 '가나'를 구분)
  const key = (s) => String(s || '').replace(/\s/g, '').toLowerCase();
  const api = { CATS, categorize, norm, key };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.Category = api;
})(typeof globalThis !== 'undefined' ? globalThis : this);
